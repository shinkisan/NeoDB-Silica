import { writeFileSync } from "node:fs";

const springs = {
  soft: { stiffness: 380, damping: 34, duration: 420 },
  snappy: { stiffness: 520, damping: 36, duration: 380 },
  bouncy: { stiffness: 420, damping: 24, duration: 420 },
};

function sampleSpring({ stiffness, damping, duration }) {
  const decay = damping / 2;
  const frequency = Math.sqrt(stiffness - decay ** 2);
  const samples = Array.from({ length: 25 }, (_, index) => {
    const time = (index / 24) * duration / 1000;
    const displacement = Math.exp(-decay * time) *
      (Math.cos(frequency * time) + (decay / frequency) * Math.sin(frequency * time));
    return Number((1 - displacement).toFixed(3));
  });
  samples[24] = 1;
  return `linear(${samples.join(", ")})`;
}

const curves = Object.entries(springs).map(([name, spring]) => [name, sampleSpring(spring)]);
writeFileSync(new URL("../src/app/motion-tokens.css", import.meta.url),
  "/* Generated by scripts/generate-motion.mjs. */\n@theme static {\n" +
  curves.map(([name, value]) => `  --ease-spring-${name}: ${value};\n`).join("") +
  "}\n");
writeFileSync(new URL("../src/lib/motion-springs.ts", import.meta.url),
  "// Generated by scripts/generate-motion.mjs.\nexport const springs = {\n" +
  curves.map(([name, value]) => `  ${name}: "${value}",\n`).join("") +
  "} as const;\n");
